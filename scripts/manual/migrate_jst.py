"""One-time Shanghai -> Tokyo wall-clock migration for production WMS.

Run only through the manual GitHub Actions workflow after the staged backend
release has passed its normal deployment. The command stops the API, makes a
verified pg_dump backup, converts the audited timestamp columns in one database
transaction, enables WMS_TIMEZONE, and checks the restarted API.

Date-only business fields and user-entered date/time fields retain their wall
clock. See PRESERVE below. The schema inventory is deliberately exact: a new
timestamp column requires another audit rather than an accidental conversion.
"""

from __future__ import annotations


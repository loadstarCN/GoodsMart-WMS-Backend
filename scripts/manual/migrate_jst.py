# These timestamps represent a date or wall-clock value chosen by a person.
# They must not be reinterpreted as an Asia/Shanghai instant. Existing signed_at
# values were checked against sign status logs: all four were user-entered.
PRESERVE = {
    ('companies', 'expired_at'),
    ('cycle_count_tasks', 'scheduled_date'),
    ('delivery_tasks', 'signed_at'),
    ('payments', 'payment_time'),  # currently no non-null production values
}


def say(message: str) -> None:
    print(f'[jst] {message}', flush=True)


def checked(command: list[str], *, env: dict[str, str] | None = None) -> None:
    subprocess.run(command, cwd=APP_DIR, env=env, check=True)


def database_settings() -> tuple[str, dict[str, str]]:
    uri = dotenv_values(ENV_FILE).get('SQLALCHEMY_DATABASE_URI')
    if not uri or not uri.startswith(('postgresql://', 'postgres://')):
        raise RuntimeError('production PostgreSQL URI is missing')
    from urllib.parse import unquote, urlparse

    parsed = urlparse(uri)
    pg_env = os.environ.copy()
    pg_env.update(
        PGHOST=parsed.hostname or '',
        PGPORT=str(parsed.port or 5432),
        PGUSER=unquote(parsed.username or ''),
        PGPASSWORD=unquote(parsed.password or ''),
        PGDATABASE=(parsed.path or '').lstrip('/'),
        PGCONNECT_TIMEOUT='5',
    )
    return uri, pg_env


def expected_columns() -> set[tuple[str, str]]:
    return {(table, column) for table, columns in TIMESTAMP_COLUMNS.items()
            for column in columns.split()}


def inspect_database(uri: str) -> None:
    with psycopg2.connect(uri, connect_timeout=5) as conn:
        with conn.cursor() as cur:
            cur.execute("SHOW TIMEZONE")
            db_timezone = cur.fetchone()[0]
            if db_timezone != 'Asia/Shanghai':
                raise RuntimeError(f'expected Asia/Shanghai database session; got {db_timezone}')
            cur.execute("""
                SELECT table_name, column_name FROM information_schema.columns
                WHERE table_schema = 'public'
                  AND data_type = 'timestamp without time zone'
            """)
            actual = set(cur.fetchall())
            expected = expected_columns()
            if actual != expected:
                raise RuntimeError(f'timestamp schema changed: missing={sorted(expected - actual)}, '
                                   f'new={sorted(actual - expected)}')
            if not PRESERVE <= expected:
                raise RuntimeError('preserved column is absent from schema inventory')
            cur.execute("SELECT to_regclass('public.wms_timezone_migrations')")
            if cur.fetchone()[0] is not None:
                raise RuntimeError('timezone migration table already exists; refusing a second run')
    say(f'preflight: {len(actual)} timestamp columns audited, '
        f'{len(PRESERVE)} user-entered columns retained')


def preflight_japan_process(*, from_env_file: bool = False) -> None:
    # Test both clocks with the staged application code while the live process
    # still uses Shanghai. This process only reads the database.
    environment = os.environ.copy()
    environment.update(FLASK_ENV='production', SCHEDULER_ENABLED='False')
    if from_env_file:
        environment.pop('WMS_TIMEZONE', None)
    else:
        environment['WMS_TIMEZONE'] = 'Asia/Tokyo'
    command = (
        'from datetime import datetime; from zoneinfo import ZoneInfo; '
        'from sqlalchemy import text; from app import app; from extensions import db; '
        'assert abs((datetime.now()-datetime.now(ZoneInfo("Asia/Tokyo")).replace(tzinfo=None)).total_seconds())<2; '
        'ctx=app.app_context(); ctx.push(); '
        'assert db.session.execute(text("SHOW TIMEZONE")).scalar()=="Asia/Tokyo"; '
        'ctx.pop()'
    )
    checked([sys.executable, '-c', command], env=environment)
    say('preflight: Python and application PostgreSQL session use Asia/Tokyo')


def health_ok(url: str, expected_commit: str) -> bool:
    try:
        with urlopen(url, timeout=5) as response:
            import json
            payload = json.load(response)
            return (response.status == 200 and payload.get('status') == 'ok'
                    and payload.get('commit') == expected_commit)
    except (OSError, ValueError, URLError):
        return False


def write_timezone_flag(old_content: bytes, old_mode: int) -> None:
    if b'WMS_TIMEZONE=' in old_content:
        raise RuntimeError('WMS_TIMEZONE is already in .env')
    temporary = ENV_FILE.with_name('.env.jst.tmp')
    with temporary.open('wb') as output:
        output.write(old_content.rstrip(b'\r\n') + b'\nWMS_TIMEZONE=Asia/Tokyo\n')
        output.flush()
        os.fsync(output.fileno())
    os.chmod(temporary, old_mode)
    os.replace(temporary, ENV_FILE)


def restore_env(old_content: bytes, old_mode: int) -> None:
    temporary = ENV_FILE.with_name('.env.jst.rollback.tmp')
    with temporary.open('wb') as output:
        output.write(old_content)
        output.flush()
        os.fsync(output.fileno())
    os.chmod(temporary, old_mode)
    os.replace(temporary, ENV_FILE)


def migrate(uri: str, backup: Path) -> None:
    with psycopg2.connect(uri, connect_timeout=5) as conn:
        with conn.cursor() as cur:
            cur.execute("SET LOCAL lock_timeout = '15s'")
            cur.execute("SET LOCAL statement_timeout = '5min'")
            cur.execute("SELECT pg_advisory_xact_lock(hashtext('wms-shanghai-to-tokyo'))")
            cur.execute("SHOW TIMEZONE")
            if cur.fetchone()[0] != 'Asia/Shanghai':
                raise RuntimeError('migration connection is not in Asia/Shanghai')
            cur.execute('SELECT id, created_at FROM activity_logs ORDER BY id DESC LIMIT 1')
            sample = cur.fetchone()
            for table, columns in TIMESTAMP_COLUMNS.items():
                shift = [column for column in columns.split()
                         if (table, column) not in PRESERVE]
                if not shift:
                    continue
                assignments = [sql.SQL('{} = ({} AT TIME ZONE %s) AT TIME ZONE %s').format(
                    sql.Identifier(column), sql.Identifier(column)) for column in shift]
                predicate = sql.SQL(' OR ').join(
                    sql.SQL('{} IS NOT NULL').format(sql.Identifier(column)) for column in shift)
                statement = sql.SQL('UPDATE {} SET {} WHERE {}').format(
                    sql.Identifier(table), sql.SQL(', ').join(assignments), predicate)
                cur.execute(statement, ['Asia/Shanghai', 'Asia/Tokyo'] * len(shift))
                say(f'{table}: {cur.rowcount} rows converted')
            # actual_shipping_date is the one date-only column WMS derives from
            # datetime.now(). Correct the rare 23:00-23:59 Shanghai completions.
            cur.execute("""
                UPDATE delivery_tasks SET actual_shipping_date = completed_at::date
                WHERE completed_at IS NOT NULL
                  AND actual_shipping_date = (completed_at - INTERVAL '1 hour')::date
                  AND actual_shipping_date <> completed_at::date
            """)
            say(f'delivery_tasks: {cur.rowcount} shipping dates corrected')
            cur.execute("""
                CREATE TABLE wms_timezone_migrations (
                    migration_key text PRIMARY KEY,
                    migrated_at timestamptz NOT NULL DEFAULT now(),
                    source_timezone text NOT NULL,
                    target_timezone text NOT NULL,
                    backup_file text NOT NULL
                )
            """)
            cur.execute("""
                INSERT INTO wms_timezone_migrations
                  (migration_key, source_timezone, target_timezone, backup_file)
                VALUES (%s, %s, %s, %s)
            """, (MIGRATION_KEY, 'Asia/Shanghai', 'Asia/Tokyo', str(backup)))
            if sample is not None:
                cur.execute('SELECT created_at FROM activity_logs WHERE id = %s', (sample[0],))
                if cur.fetchone()[0] - sample[1] != timedelta(hours=1):
                    raise RuntimeError('activity log sample failed +1 hour verification')
    say('database conversion committed')


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--apply', action='store_true', required=True)
    parser.add_argument('--health-url', default='http://127.0.0.1:5002/health')
    args = parser.parse_args()
    if os.name != 'posix' or not hasattr(time, 'tzset'):
        raise RuntimeError('run the maintenance command on the Linux API server')
    if (dotenv_values(ENV_FILE).get('WMS_TIMEZONE') or '').strip():
        raise RuntimeError('WMS_TIMEZONE is already enabled')
    for binary in ('pm2', 'pg_dump', 'pg_restore'):
        if shutil.which(binary) is None:
            raise RuntimeError(f'{binary} is unavailable')
    if subprocess.check_output(['git', 'status', '--porcelain', '--untracked-files=no'],
                               cwd=APP_DIR).strip():
        raise RuntimeError('tracked server files have local modifications')
    expected_commit = subprocess.check_output(['git', 'rev-parse', '--short=7', 'HEAD'],
                                              cwd=APP_DIR, text=True).strip()
    if not health_ok(args.health_url, expected_commit):
        raise RuntimeError('existing API health check failed; nothing changed')
    uri, pg_env = database_settings()
    inspect_database(uri)
    preflight_japan_process()
    BACKUP_DIR.mkdir(mode=0o700, parents=True, exist_ok=True)
    os.chmod(BACKUP_DIR, 0o700)
    old_content = ENV_FILE.read_bytes()
    old_mode = stat.S_IMODE(ENV_FILE.stat().st_mode)
    backup = BACKUP_DIR / ('wms-before-jst-' + datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ') + '.dump')
    stopped = False
    migrated = False
    try:
        say('stopping wms-api for the maintenance window')
        stopped = True
        checked(['pm2', 'stop', 'wms-api'])
        # An offline backup is the recovery point. Keep it outside the Git
        # checkout and only readable by the deploy account.
        checked(['pg_dump', '-Fc', '--no-owner', '--no-privileges', '-f', str(backup)], env=pg_env)
        os.chmod(backup, 0o600)
        digest_hash = hashlib.sha256()
        with backup.open('rb') as source:
            for block in iter(lambda: source.read(1024 * 1024), b''):
                digest_hash.update(block)
        digest = digest_hash.hexdigest()
        subprocess.run(['pg_restore', '--list', str(backup)], stdout=subprocess.DEVNULL,
                       check=True)
        checked(['pg_restore', '--file', os.devnull, str(backup)])
        say(f'backup verified: {backup} ({backup.stat().st_size} bytes, sha256={digest})')
        inspect_database(uri)
        write_timezone_flag(old_content, old_mode)
        migrate(uri, backup)
        migrated = True
        preflight_japan_process(from_env_file=True)
        checked(['pm2', 'restart', 'wms-api'])
        deadline = time.monotonic() + 90
        while time.monotonic() < deadline:
            if health_ok(args.health_url, expected_commit):
                say('API health check passed under Asia/Tokyo')
                stopped = False
                break
            time.sleep(3)
        else:
            raise RuntimeError('API did not pass its health check within 90 seconds')
    finally:
        if stopped:
            if not migrated:
                restore_env(old_content, old_mode)
                say('database was not converted; restored .env')
            # Once the transaction commits, keep Tokyo enabled even if health
            # fails: starting an old-timezone writer would corrupt new rows.
            try:
                checked(['pm2', 'restart', 'wms-api'])
            except subprocess.CalledProcessError:
                say('pm2 restart failed; manual recovery is required')


if __name__ == '__main__':
    main()
